function iconInfo(source: string): SvgIconInfo {
  const viewBox = source.match(/\bviewBox="([^"]+)"/)?.[1];
  const path = [...source.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map(match => match[1]).join(' ');
  if (!viewBox || !path) throw new Error('Invalid Material Symbols SVG asset.');
  return { viewBox, path };
}

